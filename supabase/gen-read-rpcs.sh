#!/usr/bin/env bash
# =============================================================================
# Writes web/src/offline/readRpcs.ts: the RPCs the app may answer from an
# offline copy (web/src/offline/readCache.ts).
#
# Taken from the database, never written by hand: every function the app may
# call that Postgres declares STABLE or IMMUTABLE and that names no volatile
# function, directly or through another, so answering one from a copy can never
# hide a write. supabase/check-read-rpcs.sh fails CI if the file and
# the database disagree.
#
# Usage:  ./supabase/gen-read-rpcs.sh
#         (needs PG* env vars pointing at a database with the migrations applied)
# =============================================================================
set -euo pipefail
cd "$(dirname "$0")/.."
# STABLE is not enough on its own. Postgres refuses an INSERT written inside a
# STABLE function, but lets one CALL a volatile function that writes (checked:
# the nested insert goes through). So a function is left off the list if its
# body names any volatile public function, directly or through another
# function that does. Matching names in the body errs towards leaving a
# function off (a name in a comment counts), which is the safe direction: a
# read left off is only not available offline.
names=$(psql -tA -v ON_ERROR_STOP=1 <<'SQL'
with recursive fns as (
  select p.oid, p.proname, p.provolatile, p.prosrc, p.prokind
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public'
),
may_write(proname) as (
  select proname from fns where provolatile = 'v'
  union
  select f.proname from fns f join may_write w
      on f.proname <> w.proname and f.prosrc ~ ('\y' || w.proname || '\s*\(')
)
select distinct p.proname
  from fns p
 where p.provolatile in ('s', 'i')
   and p.prokind = 'f'
   and has_function_privilege('authenticated', p.oid, 'EXECUTE')
   and p.proname not in (select proname from may_write)
 order by 1;
SQL
)
{
  echo "// GENERATED by supabase/gen-read-rpcs.sh from the database. Do not edit by hand."
  echo "//"
  echo "// Every function the app may call that Postgres declares STABLE or IMMUTABLE"
  echo "// and that calls no volatile function, directly or through another, so it can"
  echo "// never write. Only these RPCs are answered from an offline copy."
  echo "// supabase/check-read-rpcs.sh fails CI when this and the database disagree."
  echo "export const READ_RPCS: ReadonlySet<string> = new Set(["
  while read -r n; do [ -n "$n" ] && echo "  '$n',"; done <<< "$names"
  echo "])"
} > web/src/offline/readRpcs.ts
echo "wrote web/src/offline/readRpcs.ts ($(grep -c "^  '" web/src/offline/readRpcs.ts) functions)"
